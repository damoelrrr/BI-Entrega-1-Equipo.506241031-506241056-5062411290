CREATE TABLE dw.ctx_empresas_bogota (
    empresa_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_fuente             INTEGER,                 -- _id del recurso original
    periodo               VARCHAR(4),
    mes                   SMALLINT,
    localidad             VARCHAR(60),
    tamano_empresarial    VARCHAR(30),
    rama_actividad        VARCHAR(60),
    codigo_ciiu           VARCHAR(20),             -- 4 dígitos con cero inicial; algunas filas traen 'Sin información'
    organizacion_juridica VARCHAR(80),
    empresas_vigentes     INTEGER,
    empresas_creadas      INTEGER,
    empresas_canceladas   INTEGER
);
