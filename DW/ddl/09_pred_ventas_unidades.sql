-- Predicciones del modelo de unidades vendidas (Entrega 3).
-- Granularidad: una fila por tienda, producto y mes del conjunto de prueba (2025).
-- Las llaves permiten unir la tabla con dim_fecha, dim_tienda y dim_producto.
-- fecha_key corresponde al primer día del mes (AAAAMM01).
CREATE TABLE IF NOT EXISTS dw.pred_ventas_unidades (
    pred_key       BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_key      INTEGER       NOT NULL REFERENCES dw.dim_fecha    (fecha_key),
    tienda_key     INTEGER       NOT NULL REFERENCES dw.dim_tienda   (tienda_key),
    producto_key   INTEGER       NOT NULL REFERENCES dw.dim_producto (producto_key),
    modelo         VARCHAR(40)   NOT NULL,                  -- algoritmo elegido
    unidades_real  INTEGER       NOT NULL,
    unidades_pred  NUMERIC(10,2) NOT NULL,
    error_abs      NUMERIC(10,2) NOT NULL,                  -- valor absoluto de real menos predicho
    UNIQUE (fecha_key, tienda_key, producto_key, modelo)
);
CREATE INDEX IF NOT EXISTS ix_pred_fecha    ON dw.pred_ventas_unidades (fecha_key);
CREATE INDEX IF NOT EXISTS ix_pred_tienda   ON dw.pred_ventas_unidades (tienda_key);
CREATE INDEX IF NOT EXISTS ix_pred_producto ON dw.pred_ventas_unidades (producto_key);
