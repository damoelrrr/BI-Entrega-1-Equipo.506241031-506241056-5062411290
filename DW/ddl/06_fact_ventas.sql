-- Granularidad: una línea de venta (un producto, en una tienda, en un día)
CREATE TABLE dw.fact_ventas (
    venta_fact_key  BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_key       INTEGER NOT NULL REFERENCES dw.dim_fecha     (fecha_key),
    tienda_key      INTEGER NOT NULL REFERENCES dw.dim_tienda    (tienda_key),
    producto_key    INTEGER NOT NULL REFERENCES dw.dim_producto  (producto_key),
    descuento_key   INTEGER NOT NULL REFERENCES dw.dim_descuento (descuento_key),
    venta_id        VARCHAR(12) NOT NULL UNIQUE,  -- dimensión degenerada
    cantidad        INTEGER        NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(12,2)  NOT NULL,
    venta_bruta     NUMERIC(14,2)  NOT NULL,
    descuento       NUMERIC(14,2)  NOT NULL,
    venta_neta      NUMERIC(14,2)  NOT NULL,
    costo_total_sim NUMERIC(14,2)  NOT NULL,      -- sintético
    margen_sim      NUMERIC(14,2)  NOT NULL       -- sintético
);
CREATE INDEX ix_fact_fecha     ON dw.fact_ventas (fecha_key);
CREATE INDEX ix_fact_tienda    ON dw.fact_ventas (tienda_key);
CREATE INDEX ix_fact_producto  ON dw.fact_ventas (producto_key);
CREATE INDEX ix_fact_descuento ON dw.fact_ventas (descuento_key);
