-- Contexto F1 (DANE, EMC hoja 2.1): serie mensual de índices, base 2019 = 100
CREATE TABLE dw.ctx_emc_comercio_minorista (
    emc_id                            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha                             DATE    NOT NULL UNIQUE,   -- primer día del mes
    anio                              SMALLINT NOT NULL,
    mes                               SMALLINT NOT NULL,
    indice_sin_vehiculos              NUMERIC(10,2),
    indice_sin_combustibles_vehiculos NUMERIC(10,2)
);
